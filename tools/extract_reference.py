#!/usr/bin/env python3
"""Write config/reference/*.yml from the Pixel fonts.

Usage:
    python3 -I tools/extract_reference.py --fonttools <tree>/external/fonttools/Lib \
        --pyyaml <tree>/external/python/pyyaml/lib \
        --pixel-fonts <product/fonts of a Pixel factory image> \
        --build <Android build number>

Reads the Pixel font of each output font in config/upstream.yml. The reference describes
what tools/generate_fonts.py copies from the Pixel fonts and what tools/check_fonts.py
expects.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common

HEADER = (
    "# Generated by tools/extract_reference.py from the Pixel fonts. Do not edit.\n"
)


def script_tags(font, tag):
    if tag not in font:
        return []

    return sorted(
        str(record.ScriptTag) for record in font[tag].table.ScriptList.ScriptRecord
    )


def feature_tags(font, tag):
    if tag not in font:
        return []

    return sorted(
        {str(record.FeatureTag) for record in font[tag].table.FeatureList.FeatureRecord}
    )


def reference(font, path, build):
    os2 = font["OS/2"]
    hhea = font["hhea"]

    # Insertion order is the file order. The codepoints come last because they are long.
    return {
        "source": {
            "build": build,
            "file": os.path.basename(path),
            "version": font["name"].getDebugName(5),
            "sha256": common.file_sha256(path),
        },
        "tables": sorted(map(str, set(font.keys()) - {"GlyphOrder"})),
        "GSUB": {
            "scripts": script_tags(font, "GSUB"),
            "features": feature_tags(font, "GSUB"),
        },
        "GPOS": {
            "scripts": script_tags(font, "GPOS"),
            "features": feature_tags(font, "GPOS"),
        },
        "head": {"yMin": font["head"].yMin, "yMax": font["head"].yMax},
        # google/fonts already has the hhea and OS/2 typo values, so generate_fonts.py
        # does not set them. check_fonts.py fails if they change.
        "hhea": {
            "ascent": hhea.ascent,
            "descent": hhea.descent,
            "lineGap": hhea.lineGap,
        },
        "OS/2": {
            "usWinAscent": os2.usWinAscent,
            "usWinDescent": os2.usWinDescent,
            "sTypoAscender": os2.sTypoAscender,
            "sTypoDescender": os2.sTypoDescender,
            "sTypoLineGap": os2.sTypoLineGap,
            "fsSelection.USE_TYPO_METRICS": bool(os2.fsSelection & (1 << 7)),
            "ulUnicodeRange": sorted(os2.getUnicodeRanges()),
            "ulCodePageRange": sorted(os2.getCodePageRanges()),
        },
        "codepoints": common.format_codepoints(font.getBestCmap()),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    common.add_library_arguments(parser)
    parser.add_argument(
        "--pixel-fonts", required=True, help="product/fonts of a Pixel factory image"
    )
    parser.add_argument(
        "--build", required=True, help="Android build number, such as CP3A.261005.005"
    )
    arguments = parser.parse_args()

    common.add_library_paths(arguments)
    import yaml
    from fontTools.ttLib import TTFont

    os.makedirs(common.REFERENCE_DIRECTORY, exist_ok=True)

    for output in common.load_yaml(common.UPSTREAM_PATH)["fonts"]:
        path = os.path.join(arguments.pixel_fonts, output)
        data = reference(TTFont(path), path, arguments.build)
        reference_path = common.reference_path(output)

        with open(reference_path, "w", encoding="utf-8") as file:
            file.write(HEADER)
            yaml.dump(
                data,
                file,
                Dumper=yaml.SafeDumper,
                sort_keys=False,
                default_flow_style=False,
            )

        relative_path = os.path.relpath(reference_path, common.MODULE_DIRECTORY)
        print(f"{data['source']['sha256']}  {output} -> {relative_path}")


if __name__ == "__main__":
    main()
